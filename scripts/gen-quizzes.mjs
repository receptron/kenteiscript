// Generates src/quizzes.gen.ts, which bundles every quizzes/*.json into the Worker.
// Runs automatically before `wrangler dev` and `wrangler deploy` (see "build" in wrangler.jsonc).
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = new URL("..", import.meta.url).pathname;
const dir = join(root, "quizzes");
const files = readdirSync(dir).filter((f) => f.endsWith(".json") && !f.endsWith(".tests.json")).sort();
if (!files.length) throw new Error("No quizzes found in quizzes/");

for (const f of files) {
  const quiz = JSON.parse(readFileSync(join(dir, f), "utf8"));
  for (const key of ["meta", "rules", "questions"]) {
    if (!quiz[key]) throw new Error(`quizzes/${f}: missing "${key}"`);
  }
  const ids = new Set();
  for (const q of quiz.questions) {
    if (ids.has(q.id)) throw new Error(`quizzes/${f}: duplicate question id ${q.id}`);
    ids.add(q.id);
    if (!["Choice", "Score"].includes(q.jev?.type)) throw new Error(`quizzes/${f}: ${q.id} has no jev Choice/Score`);
  }
}

const lines = [
  "// Generated by scripts/gen-quizzes.mjs. Do not edit.",
  'import type { Quiz } from "./grading.ts";',
  ...files.map((f, i) => `import q${i} from "../quizzes/${f}";`),
  "",
  "export const quizzes: Record<string, Quiz> = {",
  ...files.map((f, i) => `  ${JSON.stringify(f.replace(/\.json$/, ""))}: q${i} as unknown as Quiz,`),
  "};",
  "",
];
// Write only on change: rewriting an identical file would make `wrangler dev` rebuild in a loop.
const out = join(root, "src", "quizzes.gen.ts");
const text = lines.join("\n");
if (!existsSync(out) || readFileSync(out, "utf8") !== text) writeFileSync(out, text);
console.log(`quizzes: ${files.map((f) => f.replace(/\.json$/, "")).join(", ")}`);
