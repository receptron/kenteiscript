// Replaces dist/types/kentei-script.d.ts, written by vue-tsc for `npm run build:plugin`, with plain
// TypeScript types. The emitted file declares the Zod schema objects, so it imports `zod`, which is
// only a devDependency (the plugin's JS bundles Zod); a consumer without Zod would get TS2307. The
// types are z.infer'red from the schema, so this script asks the type checker for each exported
// type alias in src/kentei-script.ts and writes it out expanded: still one definition of the
// format, and declarations that need nothing but gui-chat-protocol and vue.
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import ts from "typescript";

const root = new URL("..", import.meta.url).pathname;
const source = join(root, "src", "kentei-script.ts");
const program = ts.createProgram([source], {
  strict: true,
  allowImportingTsExtensions: true,
  noEmit: true,
  module: ts.ModuleKind.ESNext,
  moduleResolution: ts.ModuleResolutionKind.Bundler,
  target: ts.ScriptTarget.ES2022,
});
const checker = program.getTypeChecker();
const file = program.getSourceFile(source);
const flags = ts.TypeFormatFlags.NoTruncation | ts.TypeFormatFlags.InTypeAlias | ts.TypeFormatFlags.MultilineObjectLiterals;

const out = [
  "// Generated by scripts/gen-plugin-types.mjs from src/kentei-script.ts (the Zod schema). Plain types:",
  "// the schema itself is bundled into the plugin's JS, so these declarations need no Zod.",
];
for (const sym of checker.getExportsOfModule(checker.getSymbolAtLocation(file))) {
  const decl = sym.declarations?.find(ts.isTypeAliasDeclaration);
  if (!decl) continue;
  const text = checker.typeToString(checker.getTypeAtLocation(decl.name), decl, flags);
  if (/\bz\.|Zod/.test(text)) throw new Error(`${sym.name} did not expand to plain types: ${text.slice(0, 200)}`);
  out.push(`export type ${sym.name} = ${text};`);
}
out.push("/** Validates a parsed KenteiScript; throws one readable error listing every problem. */");
out.push("export declare function parseKenteiScript(data: unknown, name: string): KenteiScript;");
out.push("");

const types = join(root, "dist", "types");
// Reprinted through the TypeScript printer, so the expanded types are formatted like normal source.
const printed = ts.createPrinter().printFile(ts.createSourceFile("kentei-script.d.ts", out.join("\n"), ts.ScriptTarget.ES2022, false, ts.ScriptKind.TS));
writeFileSync(join(types, "kentei-script.d.ts"), printed);

// No declaration may name zod now; fail the build if one does.
const walk = (dir) => readdirSync(dir).flatMap((f) => (statSync(join(dir, f)).isDirectory() ? walk(join(dir, f)) : [join(dir, f)]));
const leaks = walk(types).filter((f) => f.endsWith(".d.ts") && /from ["']zod["']|import\(["']zod["']\)/.test(readFileSync(f, "utf8")));
if (leaks.length) throw new Error(`declarations still import zod: ${leaks.join(", ")}`);
console.log("plugin types: dist/types/kentei-script.d.ts (plain types, no zod)");
