// Generates src/quizzes.gen.ts, which bundles every KenteiScript (quizzes/*.json) into the Worker.
// Runs automatically before `wrangler dev` and `wrangler deploy` (see "build" in wrangler.jsonc).
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { parseKenteiScript } from "../src/kentei-script.ts";

const root = new URL("..", import.meta.url).pathname;
const dir = join(root, "quizzes");
const files = readdirSync(dir).filter((f) => f.endsWith(".json") && !f.endsWith(".tests.json")).sort();
if (!files.length) throw new Error("No quizzes found in quizzes/");

// Every KenteiScript is validated with the Zod schema; one bad file fails the build with a list
// of what is wrong, instead of failing a game later.
for (const f of files) parseKenteiScript(JSON.parse(readFileSync(join(dir, f), "utf8")), `quizzes/${f}`);

const lines = [
  "// Generated by scripts/gen-quizzes.mjs. Do not edit.",
  'import type { KenteiScript } from "./kentei-script.ts";',
  ...files.map((f, i) => `import q${i} from "../quizzes/${f}";`),
  "",
  "export const quizzes: Record<string, KenteiScript> = {",
  ...files.map((f, i) => `  ${JSON.stringify(f.replace(/\.json$/, ""))}: q${i} as unknown as KenteiScript,`),
  "};",
  "",
];
// Write only on change: rewriting an identical file would make `wrangler dev` rebuild in a loop.
const out = join(root, "src", "quizzes.gen.ts");
const text = lines.join("\n");
if (!existsSync(out) || readFileSync(out, "utf8") !== text) writeFileSync(out, text);
console.log(`quizzes: ${files.map((f) => f.replace(/\.json$/, "")).join(", ")}`);
